LogicalResult translateToOpenFhePkeHarness(Operation* op, llvm::raw_ostream& os,
                                           const std::string& headerInclude) {
  auto module = dyn_cast<ModuleOp>(op);
  if (!module)
    return op->emitOpError(
        "--emit-openfhe-pke-harness expects a ModuleOp at the top level");

  func::FuncOp target = findTargetKernel(module);
  if (!target)
    return module.emitOpError(
        "no target kernel found — every func.func was `main` or `*_dummy`");

  llvm::StringRef prefix = target.getSymName();
  // N is the ciphertext-arg count — take it from __encrypt__arg helpers,
  // not from the wrapper's MLIR arg count (that includes `cc` and any
  // trailing plaintext arg split_preprocessing kept in the signature).
  int n = countClientInterfaceHelpers(module, prefix, "__encrypt__arg");
  if (n <= 0)
    return target.emitOpError(
        "no <prefix>__encrypt__arg<i> helpers found in the module — did "
        "you run --openfhe-add-client-interface upstream of "
        "--emit-openfhe-pke-harness?");

  // M is the ciphertext-result count — take it from __decrypt__result
  // helpers, same reasoning.
  int m = countClientInterfaceHelpers(module, prefix, "__decrypt__result");
  if (m <= 0)
    return target.emitOpError(
        "no <prefix>__decrypt__result<i> helpers found in the module — did "
        "you run --openfhe-add-client-interface upstream of "
        "--emit-openfhe-pke-harness?");

  bool usePreprocessed = hasPreprocessingPair(module, prefix);
  emitMain(os, prefix, n, m, usePreprocessed, headerInclude);
  return success();
}

