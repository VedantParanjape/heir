// Locate the target kernel. Selection rules, in order:
//   1. Skip `main` and any `*_dummy` — biscotti scaffolding.
//   2. Skip anything containing `__` in its symbol — HEIR's AddClientInterface
//      and ConfigureCryptoContext passes generate helpers with that separator
//      (`<kernel>__encrypt__argK`, `<kernel>__generate_crypto_context`, etc).
//      Picking one of those as the "target" would double up the prefix on
//      every subsequent generated call.
//   3. Skip declarations (no body).
// The first surviving `func.func` in module order is the kernel.
func::FuncOp findTargetKernel(ModuleOp module) {
  func::FuncOp target;
  module.walk([&](func::FuncOp fn) {
    if (target) return;
    llvm::StringRef name = fn.getSymName();
    if (name == "main") return;
    if (name.ends_with("_dummy")) return;
    if (name.contains("__")) return;
    if (fn.isDeclaration()) return;
    target = fn;
  });
  return target;
}

// True if the module declares both `<prefix>__preprocessing(cc)` and
// `<prefix>__preprocessed(cc, ..., v4)`. When present, we hoist the
// preprocessing call out of the timed loop so only the compute is timed.
bool hasPreprocessingPair(ModuleOp module, llvm::StringRef prefix) {
  bool hasPreprocessing = false;
  bool hasPreprocessed = false;
  std::string prepName = (prefix + "__preprocessing").str();
  std::string precName = (prefix + "__preprocessed").str();
  module.walk([&](func::FuncOp fn) {
    if (fn.getSymName() == prepName) hasPreprocessing = true;
    if (fn.getSymName() == precName) hasPreprocessed = true;
  });
  return hasPreprocessing && hasPreprocessed;
}

// Count client-interface helpers matching `<prefix><infix><i>` for i >= 0.
// Used to derive N (ciphertext arg count) from __encrypt__arg helpers and
// M (result count) from __decrypt__result helpers, both authoritative
// because AddClientInterface only emits them for ciphertext I/O and
// doesn't count `cc` or trailing plaintext args.
int countClientInterfaceHelpers(ModuleOp module, llvm::StringRef prefix,
                                llvm::StringRef infix) {
  std::string wanted = (prefix + infix).str();
  int count = 0;
  module.walk([&](func::FuncOp fn) {
    llvm::StringRef name = fn.getSymName();
    if (!name.starts_with(wanted)) return;
    llvm::StringRef suffix = name.drop_front(wanted.size());
    int idx = 0;
    if (!suffix.empty() && !suffix.getAsInteger(/*radix=*/10, idx)) count++;
  });
  return count;
}

void emitMain(llvm::raw_ostream& os, llvm::StringRef prefix, int n, int m,
              bool usePreprocessed, const std::string& headerInclude) {
  // Strip to basename. Bazel rejects absolute-path `#include`s in
  // sandboxed builds, and even outside Bazel a relative include is
  // what the emitted bench.cpp needs (kernel.h sits next to it in the
  // output directory). If the CLI arg came in as
  // /some/path/kernel.h, we keep only `kernel.h`.
  llvm::StringRef includeBasename = headerInclude;
  auto slash = includeBasename.find_last_of("/\\");
  if (slash != llvm::StringRef::npos)
    includeBasename = includeBasename.drop_front(slash + 1);

  os << "// AUTO-GENERATED by heir-translate --emit-openfhe-pke-harness.\n"
     << "// Kernel: " << prefix << "  (N = " << n
     << " ciphertext args, M = " << m << " ciphertext results)\n"
     << "//\n"
     << "// Workload-specific values (compile-time `size`, input generators,\n"
     << "// reference computation) live in bench_hooks.h — see its\n"
     << "// documentation for the required namespace members.\n"
     << "//\n"
     << "// Only kernel execution is timed. Setup (context, keys, encrypt,\n"
     << "// reference compute) runs once outside the timed region; the\n"
     << "// per-iteration correctness check is guarded by PauseTiming so it\n"
     << "// isn't counted either. A reference mismatch stops the benchmark\n"
     << "// via state.SkipWithError so a broken kernel can't score green.\n\n"
     << "#include <cstdint>\n"
     << "#include <functional>\n"
     << "#include <vector>\n\n"
     << "#include \"benchmark/benchmark.h\"  // from @google_benchmark\n"
     << "#include \"bench_hooks.h\"\n"
     << "#include \"" << includeBasename << "\"\n\n"
     << "static void BM_" << prefix << "(benchmark::State& state) {\n"
     << "  constexpr int size = bench_hooks::SIZE;\n"
     << "  auto A = bench_hooks::gen_input_A(size, /*seed=*/42);\n"
     << "  auto B = bench_hooks::gen_input_B(size, /*seed=*/43);\n"
     << "  auto expected = bench_hooks::reference(A, B);\n\n"
     << "  auto cc = " << prefix << "__generate_crypto_context();\n"
     << "  auto keys = cc->KeyGen();\n"
     << "  " << prefix << "__configure_crypto_context(cc, keys.secretKey);\n\n"
     << "  // Split: N = " << n << " ciphertext args baked in at emit time.\n"
     << "  // First ⌈N/2⌉ get A, remaining ⌊N/2⌋ get B (biscotti\n"
     << "  // convention). Emitted inline so the split adapts per variant\n"
     << "  // (baseline vs hoisted may compile to different N).\n"
     << "  std::vector<std::vector<int32_t>> args_data;\n"
     << "  args_data.reserve(" << n << ");\n";
  int halfCount = (n + 1) / 2;
  for (int i = 0; i < n; ++i) {
    os << "  args_data.push_back(" << (i < halfCount ? 'A' : 'B') << ");\n";
  }
  for (int i = 0; i < n; ++i) {
    os << "  auto arg" << i << " = " << prefix << "__encrypt__arg" << i
       << "(cc, args_data[" << i << "], keys.publicKey);\n";
  }
  if (usePreprocessed) {
    os << "\n"
       << "  // Preprocessing produces per-kernel plaintexts (masks, twiddle\n"
       << "  // constants, etc). Hoisted out of the timed loop so only the\n"
       << "  // ct-ct compute is measured.\n"
       << "  auto preprocessed = " << prefix << "__preprocessing(cc);\n";
  }
  // Helper to deep-clone a vector of Ciphertext shared_ptrs. OpenFHE
  // uses shared_ptr semantics for Ciphertext<T>, so passing arg0..argN
  // by value into the kernel copies the SHARED handles — any in-place
  // op inside the kernel (EvalAddInPlace / EvalMultInPlace) mutates
  // the underlying ct, which leaks back to the original arg vectors.
  // Google Benchmark runs the loop body multiple times to converge on a
  // stable measurement; without deep cloning, iterations after the
  // first see mutated inputs and produce wrong results.
  os << "\n"
     << "  auto __clone_ct_vec = [](const std::vector<CiphertextT>& v) {\n"
     << "    std::vector<CiphertextT> out;\n"
     << "    out.reserve(v.size());\n"
     << "    for (const auto& ct : v) out.push_back(ct->Clone());\n"
     << "    return out;\n"
     << "  };\n\n"
     << "  for (auto _ : state) {\n"
     << "    // Deep-clone inputs so in-place kernel ops don't leak\n"
     << "    // mutation across benchmark iterations. Cloning is cheap\n"
     << "    // relative to the kernel body but not free, so pause the\n"
     << "    // timer while we do it.\n"
     << "    state.PauseTiming();\n";
  for (int i = 0; i < n; ++i) {
    os << "    auto arg" << i << "_iter = __clone_ct_vec(arg" << i << ");\n";
  }
  os << "    state.ResumeTiming();\n\n"
     << "    auto result = " << prefix
     << (usePreprocessed ? "__preprocessed" : "") << "(cc";
  for (int i = 0; i < n; ++i) os << ", arg" << i << "_iter";
  if (usePreprocessed) os << ", preprocessed";
  os << ");\n"
     << "    benchmark::DoNotOptimize(result);\n\n"
     << "    // Decrypt + verify excluded from timing. Timer must be\n"
     << "    // running at loop-body exit (google_benchmark's internal\n"
     << "    // finalization calls StopTimer, which asserts on running_).\n"
     << "    // So Resume before every path that exits the body: normal\n"
     << "    // fall-through and the SkipWithError break.\n"
     << "    state.PauseTiming();\n"
     << "    std::vector<int32_t> got;\n";
  // When there is more than one result ciphertext, the kernel returns an
  // OpenFHE-emitter-generated struct with fields `.arg0, .arg1, ...` (one
  // per SSA result). See OpenFhePkeEmitter.cpp:440. For a single result,
  // the kernel returns the ciphertext vector directly.
  //
  // Merge policy: each `__decrypt__result<i>` returns a full-sized vector
  // whose size equals the user-facing original tensor, with zeros at every
  // index that this particular result does NOT own (partial layouts). To
  // reconstruct the full output we superimpose them via element-wise sum —
  // since the per-result layouts partition the user's index space, at most
  // one result has a nonzero at any given index, so summing recovers the
  // full logical output regardless of how many result cts the kernel has.
  for (int i = 0; i < m; ++i) {
    std::string resultExpr =
        (m > 1) ? ("result.arg" + std::to_string(i)) : "result";
    os << "    {\n"
       << "      auto r" << i << " = " << prefix << "__decrypt__result" << i
       << "(cc, " << resultExpr << ", keys.secretKey);\n";
    if (m == 1) {
      // Single result: preserve the historical behavior — decrypt output
      // IS the got vector.
      os << "      got.insert(got.end(), r" << i << ".begin(), r" << i
         << ".end());\n";
    } else {
      // Multi-result: sum-superimpose into `got`, resizing as needed to
      // fit the widest per-result vector. First non-empty result seeds the
      // size; subsequent ones add in place.
      os << "      if (got.size() < r" << i << ".size()) got.resize(r" << i
         << ".size(), 0);\n"
         << "      for (size_t __i = 0; __i < r" << i
         << ".size(); ++__i) got[__i] += r" << i << "[__i];\n";
    }
    os << "    }\n";
  }
  // google_benchmark 1.9.x asserts on ResumeTiming after SkipWithError
  // (the state is marked !running_ && skipped_, and ResumeTiming's precondition
  // includes !skipped()). Just break out — benchmark's finalization handles
  // a paused+skipped state correctly.
  os << "    if (got != expected) {\n"
     << "      state.SkipWithError(\"decrypted output disagrees with "
        "reference\");\n"
     << "      break;\n"
     << "    }\n"
     << "    state.ResumeTiming();\n"
     << "  }\n"
     << "}\n\n"
     << "BENCHMARK(BM_" << prefix << ")->Name(\"" << prefix
     << "\")->Unit(benchmark::kMillisecond);\n\n"
     << "BENCHMARK_MAIN();\n";
}

