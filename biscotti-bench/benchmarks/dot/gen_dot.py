#!/usr/bin/env python3
"""
Emit a recursive-dot MLIR file for a given vector length N.

Recursion shape (mirrors `mm6x6-2x2-of-3x3.mlir`):
  * @dot(v1, v2, n) with `n` as the `biscotti.progress_argument`.
  * Base case: n <= 3 — direct compute of a[0]*b[0] + a[1]*b[1] + a[2]*b[2]
    (3 muls + 2 adds).
  * Recursive branch: split each input in half (v_left = first `n/2`,
    v_right = remaining), issue two recursive calls, add the two partial
    dots.
  * Recursion terminates cleanly when N == 3 * 2^k, i.e. sizes:
        3, 6, 12, 24, 48, 96, 192, 384, 768, 1536, 3072, ...

Usage:
  python3 gen_dot.py 3072              # writes src/dot_3072.mlir
  python3 gen_dot.py --all             # writes src/dot_{3,6,12,...,3072}.mlir
  python3 gen_dot.py 384 -o path.mlir  # explicit output path
"""

import argparse
import os
import sys
import textwrap

# Sizes that recursively halve down to exactly 3. All are 3 * 2^k.
DEFAULT_SIZES = [3, 6, 12, 24, 48, 96, 192, 384, 768, 1536, 3072]


def emit_mlir(N: int) -> str:
  """Return the MLIR text for a recursive dot of length N."""
  if N < 3:
    raise ValueError(f"N must be >= 3, got {N}")

  # Validate N is 3 * 2^k so recursion halves cleanly to the n=3 base
  # case. (Uneven splits would need additional base cases for n=1, n=2.)
  n = N
  while n > 3:
    if n % 2 != 0:
      raise ValueError(
          f"N={N} does not recursively halve to base=3. "
          "Use one of: 3, 6, 12, 24, 48, 96, 192, 384, 768, 1536, 3072, ..."
      )
    n //= 2

  return textwrap.dedent(f"""\
        // Recursive dot product of two length-{N} vectors.
        // Base case: n<=3 — direct 3-element dot (3 muls + 2 adds).
        // Recursion: split each vector into two halves of length n/2, issue
        // two recursive calls, add the two partial dots.
        //
        // Generated by benchmarks/dot/gen_dot.py — do not hand-edit.

        !val = i32
        !svec = !secret.secret<tensor<?x!val>>

        func.func @dot(
            %v1 : !svec,
            %v2 : !svec,
            %n  : !val {{ biscotti.progress_argument = 2 }}
        ) -> !svec {{

            %c3 = arith.constant 3 : !val
            %c2v = arith.constant 2 : !val

            %cond = arith.cmpi sle, %n, %c3 : !val
            cf.cond_br %cond, ^base, ^recursive {{ biscotti.base_condition = 0 }}

        ^base:
            // Base case: 3-element dot product.
            // Result is a 1-element tensor holding the scalar sum.
            %result_base = secret.generic(%v1 : !svec, %v2 : !svec) {{
                ^bb0(%a: tensor<?x!val>, %b: tensor<?x!val>):
                    %c0_i = arith.constant 0 : index
                    %c1_i = arith.constant 1 : index
                    %c2_i = arith.constant 2 : index

                    %a0 = tensor.extract %a[%c0_i] : tensor<?x!val>
                    %a1 = tensor.extract %a[%c1_i] : tensor<?x!val>
                    %a2 = tensor.extract %a[%c2_i] : tensor<?x!val>

                    %b0 = tensor.extract %b[%c0_i] : tensor<?x!val>
                    %b1 = tensor.extract %b[%c1_i] : tensor<?x!val>
                    %b2 = tensor.extract %b[%c2_i] : tensor<?x!val>

                    %m0 = arith.muli %a0, %b0 : !val
                    %m1 = arith.muli %a1, %b1 : !val
                    %m2 = arith.muli %a2, %b2 : !val

                    // recursive_sum([m0, m1, m2]) = m0 + (m1 + m2)
                    %s0 = arith.addi %m1, %m2 : !val
                    %s1 = arith.addi %m0, %s0 : !val

                    %out = tensor.from_elements %s1 : tensor<1x!val>
                    %out_cast = tensor.cast %out : tensor<1x!val> to tensor<?x!val>
                    secret.yield %out_cast : tensor<?x!val>
            }} -> (!svec)
            return %result_base : !svec

        ^recursive:
            // Split each input into first-half and second-half. For N = 3*2^k
            // both halves are equal, so we use `half` for both slice lengths.
            %half = arith.divsi %n, %c2v : !val
            %half_idx = arith.index_cast %half : !val to index

            // v1_left = v1[0 .. half)
            %v1_left = secret.generic(%v1 : !svec, %half_idx : index) {{
                ^bb0(%a: tensor<?x!val>, %h: index):
                    %out = tensor.generate %h {{
                        ^bb0(%i: index):
                            %v = tensor.extract %a[%i] : tensor<?x!val>
                            tensor.yield %v : !val
                    }} : tensor<?x!val>
                    secret.yield %out : tensor<?x!val>
            }} -> (!svec)

            // v1_right = v1[half .. n)
            %v1_right = secret.generic(%v1 : !svec, %half_idx : index) {{
                ^bb0(%a: tensor<?x!val>, %h: index):
                    %out = tensor.generate %h {{
                        ^bb0(%i: index):
                            %src = arith.addi %i, %h : index
                            %v = tensor.extract %a[%src] : tensor<?x!val>
                            tensor.yield %v : !val
                    }} : tensor<?x!val>
                    secret.yield %out : tensor<?x!val>
            }} -> (!svec)

            // v2_left = v2[0 .. half)
            %v2_left = secret.generic(%v2 : !svec, %half_idx : index) {{
                ^bb0(%a: tensor<?x!val>, %h: index):
                    %out = tensor.generate %h {{
                        ^bb0(%i: index):
                            %v = tensor.extract %a[%i] : tensor<?x!val>
                            tensor.yield %v : !val
                    }} : tensor<?x!val>
                    secret.yield %out : tensor<?x!val>
            }} -> (!svec)

            // v2_right = v2[half .. n)
            %v2_right = secret.generic(%v2 : !svec, %half_idx : index) {{
                ^bb0(%a: tensor<?x!val>, %h: index):
                    %out = tensor.generate %h {{
                        ^bb0(%i: index):
                            %src = arith.addi %i, %h : index
                            %v = tensor.extract %a[%src] : tensor<?x!val>
                            tensor.yield %v : !val
                    }} : tensor<?x!val>
                    secret.yield %out : tensor<?x!val>
            }} -> (!svec)

            // Two recursive calls on half-length inputs.
            %t0 = call @dot(%v1_left,  %v2_left,  %half) {{ biscotti.recursive_call = 0 }} : (!svec, !svec, !val) -> !svec
            %t1 = call @dot(%v1_right, %v2_right, %half) {{ biscotti.recursive_call = 1 }} : (!svec, !svec, !val) -> !svec

            // Sum the two partial dots (each a 1-element tensor).
            %result = secret.generic(%t0 : !svec, %t1 : !svec) {{
                ^bb0(%x: tensor<?x!val>, %y: tensor<?x!val>):
                    %s = arith.addi %x, %y : tensor<?x!val>
                    secret.yield %s : tensor<?x!val>
            }} -> (!svec)

            return %result : !svec
        }}

        // Entry point: dot product of two length-{N} static vectors,
        // producing a 1-element static output.
        !inputvec = !secret.secret<tensor<{N}xi32>>
        !outputvec = !secret.secret<tensor<1xi32>>

        func.func @main(%v1 : !inputvec, %v2 : !inputvec) -> !outputvec {{
            %cn = arith.constant {N} : !val

            %v1_dyn = secret.generic(%v1 : !inputvec) {{
            ^bb0(%a: tensor<{N}xi32>):
                %cast = tensor.cast %a : tensor<{N}xi32> to tensor<?xi32>
                secret.yield %cast : tensor<?xi32>
            }} -> !svec

            %v2_dyn = secret.generic(%v2 : !inputvec) {{
            ^bb0(%b: tensor<{N}xi32>):
                %cast = tensor.cast %b : tensor<{N}xi32> to tensor<?xi32>
                secret.yield %cast : tensor<?xi32>
            }} -> !svec

            %result_dyn = call @dot(%v1_dyn, %v2_dyn, %cn)
                {{ biscotti.call = 0 }} : (!svec, !svec, !val) -> !svec

            %result_static = secret.generic(%result_dyn : !svec) {{
            ^bb0(%r: tensor<?xi32>):
                %cast = tensor.cast %r : tensor<?xi32> to tensor<1xi32>
                secret.yield %cast : tensor<1xi32>
            }} -> !outputvec

            return %result_static : !outputvec
        }}
        """)


def main():
  ap = argparse.ArgumentParser(
      description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
  )
  ap.add_argument(
      "N",
      nargs="?",
      type=int,
      help="vector length (must be 3 * 2^k for some k>=0)",
  )
  ap.add_argument(
      "-o", "--output", help="output path (default: src/dot_<N>.mlir)"
  )
  ap.add_argument(
      "--all",
      action="store_true",
      help=f"emit all default sizes: {DEFAULT_SIZES}",
  )
  args = ap.parse_args()

  here = os.path.dirname(os.path.abspath(__file__))
  src_dir = os.path.join(here, "src")
  os.makedirs(src_dir, exist_ok=True)

  if args.all:
    for n in DEFAULT_SIZES:
      path = os.path.join(src_dir, f"dot_{n}.mlir")
      with open(path, "w") as f:
        f.write(emit_mlir(n))
      print(f"wrote {path}")
    return

  if args.N is None:
    ap.error("give a size N (or --all)")
  path = args.output or os.path.join(src_dir, f"dot_{args.N}.mlir")
  with open(path, "w") as f:
    f.write(emit_mlir(args.N))
  print(f"wrote {path}")


if __name__ == "__main__":
  main()
