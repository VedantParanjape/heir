#!/usr/bin/env python3
"""
Emit a recursive convolution MLIR file for a given image size N.

Both image AND filter are encrypted (matches coyote's benchmark
convention). The base case does 9 ct-ct multiplications between
image pixels and filter values, then an 8-way tree reduce.

Recursion shape (mirrors `mm6x6-2x2-of-3x3.mlir`, but with 4-way fan-out
and no inter-level pairwise adds because each sub-output covers a
disjoint region of the parent output):

  * @conv(image, filter, n)  with `n` as `biscotti.progress_argument`.
    `filter` is threaded unchanged through every recursive call — only
    the base case reads it.
  * Base case (n <= 3): direct 3x3 convolution producing 1 output scalar
    (9 ct-ct muls + 8 adds).
  * Recursive branch (n > 3): split image into 4 OVERLAPPING tiles of
    side (n/2 + 1) at corner offsets (0,0), (0,off), (off,0), (off,off)
    where off = n - (n/2 + 1). Each recurses with the SAME filter. The
    4 sub-outputs are stitched into a 2x2 grid to form the (n-2)x(n-2)
    parent output.

Size ladder (input side): the recurrence N_{k+1} = 2*N_k - 2 with the
base case fed by N=3 yields  3, 4, 6, 10, 18, 34, 66, 130, 258, ....
Only these sizes halve cleanly to the 3x3 base (output side N-2 must be
even at every level so it splits evenly into halves; N=3 is the odd
exception because it IS the base, no recursion happens).

Usage:
  python3 gen_conv.py 18                # writes src/conv_18.mlir
  python3 gen_conv.py --all             # writes src/conv_{3,4,6,...}.mlir
  python3 gen_conv.py 66 -o path.mlir   # explicit output path
"""

import argparse
import os
import textwrap

# Sizes such that recursion halves cleanly to the 3x3 base case.
# N=3 base + N_{k+1} = 2*N_k - 2. Extend by editing here.
DEFAULT_SIZES = [3, 4, 6, 10, 18, 34, 66, 130]


def _valid_ladder(N_max: int):
  """Return the recursion ladder up to at least N_max, as a set."""
  sizes = {3}
  n = 4
  while n <= N_max:
    sizes.add(n)
    n = 2 * n - 2
  return sizes


def emit_flat_base_case(N: int = 3) -> str:
  """Return MLIR for a flat (non-recursive) 3x3 conv producing a 1x1 output.

  Used for the base-case size N=3 only. If we shipped the recursive
  template at N=3 the pass would try to unroll a function whose only
  branch is the base case, which trips a cleanup assertion in
  RecursiveCallVectorization (nothing to vectorize but the pass still
  reaches its arg-erase step). The flat form has no `@conv` function at
  all — just an @main that does the compute inline.

  Two secret inputs: image (9 elements) and filter (9 elements).
  """
  assert N == 3, "flat base-case emitter only fires at N=3"

  idx_lines = "\n".join(
      f"                %c{i} = arith.constant {i} : index" for i in range(9)
  )
  img_extract_lines = "\n".join(
      f"                %p{i} = tensor.extract %im[%c{i}] : tensor<9xi32>"
      for i in range(9)
  )
  filt_extract_lines = "\n".join(
      f"                %f{i} = tensor.extract %f[%c{i}] : tensor<9xi32>"
      for i in range(9)
  )
  mul_lines = "\n".join(
      f"                %m{i} = arith.muli %p{i}, %f{i} : i32" for i in range(9)
  )

  return textwrap.dedent(f"""\
        // Flat (non-recursive) 3x3 convolution — base case for the recursive
        // conv template. Applies a secret 3x3 filter to a secret 3x3 image
        // producing 1 output scalar. Both inputs encrypted; 9 ct-ct muls +
        // 8 adds. Emitted here because the recursive template's @conv would
        // have nothing to unroll at n=3, which trips a cleanup assertion in
        // RecursiveCallVectorization.
        //
        // Generated by benchmarks/conv/gen_conv.py — do not hand-edit.

        !inputvec   = !secret.secret<tensor<9xi32>>
        !filterinput = !secret.secret<tensor<9xi32>>
        !outputvec  = !secret.secret<tensor<1xi32>>

        func.func @main(%img : !inputvec, %filter : !filterinput) -> !outputvec {{
            %result = secret.generic(%img : !inputvec, %filter : !filterinput) {{
            ^body(%im: tensor<9xi32>, %f: tensor<9xi32>):
{idx_lines}
{img_extract_lines}

{filt_extract_lines}

{mul_lines}

                // Tree reduce: 9 partial products → 1 scalar (8 adds).
                %s01 = arith.addi %m0, %m1 : i32
                %s23 = arith.addi %m2, %m3 : i32
                %s45 = arith.addi %m4, %m5 : i32
                %s67 = arith.addi %m6, %m7 : i32
                %s0123 = arith.addi %s01, %s23 : i32
                %s4567 = arith.addi %s45, %s67 : i32
                %s01234567 = arith.addi %s0123, %s4567 : i32
                %s = arith.addi %s01234567, %m8 : i32

                %init = arith.constant dense<0> : tensor<1xi32>
                %out = tensor.insert %s into %init[%c0] : tensor<1xi32>
                secret.yield %out : tensor<1xi32>
            }} -> !outputvec

            return %result : !outputvec
        }}
        """)


def emit_mlir(N: int) -> str:
  """Return MLIR for a recursive conv of image size NxN."""
  if N < 3:
    raise ValueError(f"N must be >= 3, got {N}")

  ladder = _valid_ladder(max(N, DEFAULT_SIZES[-1]))
  if N not in ladder:
    raise ValueError(
        f"N={N} does not sit on the recursion ladder. "
        f"Valid sizes: {sorted(ladder)}"
    )

  if N == 3:
    return emit_flat_base_case(N)

  out_side = N - 2
  input_elems = N * N
  output_elems = out_side * out_side

  return textwrap.dedent(f"""\
        // Recursive 3x3 convolution over a length-{input_elems} (flattened {N}x{N})
        // image, using a secret 3x3 filter. Both inputs are encrypted
        // (image and filter) — the base case does 9 ct-ct multiplications
        // between image pixels and filter values, then 8 adds. Filter is
        // threaded unchanged through every recursive call; only the base
        // case reads it. Valid (no-padding) output length is {output_elems}
        // (flattened {out_side}x{out_side}).
        //
        // Generated by benchmarks/conv/gen_conv.py — do not hand-edit.

        !val  = i32
        !svec = !secret.secret<tensor<?x!val>>

        func.func @conv(
            %img    : !svec,
            %filter : !svec,
            %n      : !val {{ biscotti.progress_argument = 2 }}
        ) -> !svec {{

            %c2v = arith.constant 2 : !val
            %c3v = arith.constant 3 : !val

            %cond = arith.cmpi sle, %n, %c3v : !val
            cf.cond_br %cond, ^base, ^recursive {{ biscotti.base_condition = 0 }}

        ^base:
            // 3x3 image × secret 3x3 filter → 1 scalar. 9 ct-ct muls + 8 adds.
            %result_base = secret.generic(%img : !svec, %filter : !svec) {{
                ^bb0(%im: tensor<?x!val>, %f: tensor<?x!val>):
                    %c0_i = arith.constant 0 : index
                    %c1_i = arith.constant 1 : index
                    %c2_i = arith.constant 2 : index
                    %c3_i = arith.constant 3 : index
                    %c4_i = arith.constant 4 : index
                    %c5_i = arith.constant 5 : index
                    %c6_i = arith.constant 6 : index
                    %c7_i = arith.constant 7 : index
                    %c8_i = arith.constant 8 : index

                    %p0 = tensor.extract %im[%c0_i] : tensor<?x!val>
                    %p1 = tensor.extract %im[%c1_i] : tensor<?x!val>
                    %p2 = tensor.extract %im[%c2_i] : tensor<?x!val>
                    %p3 = tensor.extract %im[%c3_i] : tensor<?x!val>
                    %p4 = tensor.extract %im[%c4_i] : tensor<?x!val>
                    %p5 = tensor.extract %im[%c5_i] : tensor<?x!val>
                    %p6 = tensor.extract %im[%c6_i] : tensor<?x!val>
                    %p7 = tensor.extract %im[%c7_i] : tensor<?x!val>
                    %p8 = tensor.extract %im[%c8_i] : tensor<?x!val>

                    %f0 = tensor.extract %f[%c0_i] : tensor<?x!val>
                    %f1 = tensor.extract %f[%c1_i] : tensor<?x!val>
                    %f2 = tensor.extract %f[%c2_i] : tensor<?x!val>
                    %f3 = tensor.extract %f[%c3_i] : tensor<?x!val>
                    %f4 = tensor.extract %f[%c4_i] : tensor<?x!val>
                    %f5 = tensor.extract %f[%c5_i] : tensor<?x!val>
                    %f6 = tensor.extract %f[%c6_i] : tensor<?x!val>
                    %f7 = tensor.extract %f[%c7_i] : tensor<?x!val>
                    %f8 = tensor.extract %f[%c8_i] : tensor<?x!val>

                    %m0 = arith.muli %p0, %f0 : !val
                    %m1 = arith.muli %p1, %f1 : !val
                    %m2 = arith.muli %p2, %f2 : !val
                    %m3 = arith.muli %p3, %f3 : !val
                    %m4 = arith.muli %p4, %f4 : !val
                    %m5 = arith.muli %p5, %f5 : !val
                    %m6 = arith.muli %p6, %f6 : !val
                    %m7 = arith.muli %p7, %f7 : !val
                    %m8 = arith.muli %p8, %f8 : !val

                    // Tree reduce: 9 partial products → 1 scalar (8 adds).
                    %s01 = arith.addi %m0, %m1 : !val
                    %s23 = arith.addi %m2, %m3 : !val
                    %s45 = arith.addi %m4, %m5 : !val
                    %s67 = arith.addi %m6, %m7 : !val
                    %s0123 = arith.addi %s01, %s23 : !val
                    %s4567 = arith.addi %s45, %s67 : !val
                    %s01234567 = arith.addi %s0123, %s4567 : !val
                    %s = arith.addi %s01234567, %m8 : !val

                    %out = tensor.from_elements %s : tensor<1x!val>
                    %out_cast = tensor.cast %out : tensor<1x!val> to tensor<?x!val>
                    secret.yield %out_cast : tensor<?x!val>
            }} -> (!svec)
            return %result_base : !svec

        ^recursive:
            // tile_size = n/2 + 1  (each of the 4 sub-tiles is tile_size x tile_size)
            // out_side  = n - 2    (parent output side)
            // half_out  = (n-2)/2  (each sub-output side; = tile_size - 2)
            // offset    = n - tile_size = n/2 - 1  (top-left corner of right/bottom tiles)
            %n_minus_2 = arith.subi %n, %c2v : !val
            %half_out  = arith.divsi %n_minus_2, %c2v : !val
            %tile_size = arith.addi %half_out, %c2v : !val
            %tile_sq   = arith.muli %tile_size, %tile_size : !val
            %offset    = arith.subi %n, %tile_size : !val
            %out_sq    = arith.muli %n_minus_2, %n_minus_2 : !val

            %n_idx         = arith.index_cast %n         : !val to index
            %tile_size_idx = arith.index_cast %tile_size : !val to index
            %tile_sq_idx   = arith.index_cast %tile_sq   : !val to index
            %offset_idx    = arith.index_cast %offset    : !val to index
            %half_out_idx  = arith.index_cast %half_out  : !val to index
            %out_sq_idx    = arith.index_cast %out_sq    : !val to index
            %n_minus_2_idx = arith.index_cast %n_minus_2 : !val to index

            // --- 4 overlapping tile extractions ------------------------------
            // TL: corner (0, 0)          — no row/col offset
            %tl = secret.generic(%img : !svec, %tile_size_idx : index, %n_idx : index, %tile_sq_idx : index) {{
                ^bb0(%im: tensor<?x!val>, %ts: index, %nn: index, %tsq: index):
                    %out = tensor.generate %tsq {{
                        ^bb0(%i: index):
                            %row = arith.divui %i, %ts : index
                            %col = arith.remui %i, %ts : index
                            %src = arith.muli %row, %nn : index
                            %src1 = arith.addi %src, %col : index
                            %v = tensor.extract %im[%src1] : tensor<?x!val>
                            tensor.yield %v : !val
                    }} : tensor<?x!val>
                    secret.yield %out : tensor<?x!val>
            }} -> (!svec)

            // TR: corner (0, offset)     — col shifted by offset
            %tr = secret.generic(%img : !svec, %tile_size_idx : index, %n_idx : index, %tile_sq_idx : index, %offset_idx : index) {{
                ^bb0(%im: tensor<?x!val>, %ts: index, %nn: index, %tsq: index, %off: index):
                    %out = tensor.generate %tsq {{
                        ^bb0(%i: index):
                            %row = arith.divui %i, %ts : index
                            %col = arith.remui %i, %ts : index
                            %col_s = arith.addi %col, %off : index
                            %src = arith.muli %row, %nn : index
                            %src1 = arith.addi %src, %col_s : index
                            %v = tensor.extract %im[%src1] : tensor<?x!val>
                            tensor.yield %v : !val
                    }} : tensor<?x!val>
                    secret.yield %out : tensor<?x!val>
            }} -> (!svec)

            // BL: corner (offset, 0)     — row shifted by offset
            %bl = secret.generic(%img : !svec, %tile_size_idx : index, %n_idx : index, %tile_sq_idx : index, %offset_idx : index) {{
                ^bb0(%im: tensor<?x!val>, %ts: index, %nn: index, %tsq: index, %off: index):
                    %out = tensor.generate %tsq {{
                        ^bb0(%i: index):
                            %row = arith.divui %i, %ts : index
                            %col = arith.remui %i, %ts : index
                            %row_s = arith.addi %row, %off : index
                            %src = arith.muli %row_s, %nn : index
                            %src1 = arith.addi %src, %col : index
                            %v = tensor.extract %im[%src1] : tensor<?x!val>
                            tensor.yield %v : !val
                    }} : tensor<?x!val>
                    secret.yield %out : tensor<?x!val>
            }} -> (!svec)

            // BR: corner (offset, offset) — both row and col shifted
            %br = secret.generic(%img : !svec, %tile_size_idx : index, %n_idx : index, %tile_sq_idx : index, %offset_idx : index) {{
                ^bb0(%im: tensor<?x!val>, %ts: index, %nn: index, %tsq: index, %off: index):
                    %out = tensor.generate %tsq {{
                        ^bb0(%i: index):
                            %row = arith.divui %i, %ts : index
                            %col = arith.remui %i, %ts : index
                            %row_s = arith.addi %row, %off : index
                            %col_s = arith.addi %col, %off : index
                            %src = arith.muli %row_s, %nn : index
                            %src1 = arith.addi %src, %col_s : index
                            %v = tensor.extract %im[%src1] : tensor<?x!val>
                            tensor.yield %v : !val
                    }} : tensor<?x!val>
                    secret.yield %out : tensor<?x!val>
            }} -> (!svec)

            // --- 4 recursive calls on tile_size x tile_size sub-images -------
            // Same %filter passed unchanged to all 4 siblings.
            %o_tl = call @conv(%tl, %filter, %tile_size) {{ biscotti.recursive_call = 0 }} : (!svec, !svec, !val) -> !svec
            %o_tr = call @conv(%tr, %filter, %tile_size) {{ biscotti.recursive_call = 1 }} : (!svec, !svec, !val) -> !svec
            %o_bl = call @conv(%bl, %filter, %tile_size) {{ biscotti.recursive_call = 2 }} : (!svec, !svec, !val) -> !svec
            %o_br = call @conv(%br, %filter, %tile_size) {{ biscotti.recursive_call = 3 }} : (!svec, !svec, !val) -> !svec

            // --- Stitch 4 (half_out x half_out) sub-outputs into (n-2) x (n-2)
            // No pairwise adds — sub-outputs cover disjoint output regions.
            %result = secret.generic(
                %o_tl : !svec, %o_tr : !svec, %o_bl : !svec, %o_br : !svec,
                %half_out_idx : index, %n_minus_2_idx : index, %out_sq_idx : index
            ) {{
                ^bb0(%tl_v: tensor<?x!val>, %tr_v: tensor<?x!val>,
                     %bl_v: tensor<?x!val>, %br_v: tensor<?x!val>,
                     %h: index, %nm2: index, %osq: index):
                    %out = tensor.generate %osq {{
                        ^bb0(%i: index):
                            %row = arith.divui %i, %nm2 : index
                            %col = arith.remui %i, %nm2 : index
                            %row_local = arith.remui %row, %h : index
                            %col_local = arith.remui %col, %h : index
                            %local_idx = arith.muli %row_local, %h : index
                            %local_idx1 = arith.addi %local_idx, %col_local : index

                            %v_tl = tensor.extract %tl_v[%local_idx1] : tensor<?x!val>
                            %v_tr = tensor.extract %tr_v[%local_idx1] : tensor<?x!val>
                            %v_bl = tensor.extract %bl_v[%local_idx1] : tensor<?x!val>
                            %v_br = tensor.extract %br_v[%local_idx1] : tensor<?x!val>

                            %is_top  = arith.cmpi ult, %row, %h : index
                            %is_left = arith.cmpi ult, %col, %h : index

                            %top_val = arith.select %is_left, %v_tl, %v_tr : !val
                            %bot_val = arith.select %is_left, %v_bl, %v_br : !val
                            %val = arith.select %is_top, %top_val, %bot_val : !val

                            tensor.yield %val : !val
                    }} : tensor<?x!val>
                    secret.yield %out : tensor<?x!val>
            }} -> (!svec)

            return %result : !svec
        }}

        // Entry: {N}x{N} image + 3x3 filter → ({out_side}x{out_side}) output.
        !inputvec    = !secret.secret<tensor<{input_elems}xi32>>
        !filterinput = !secret.secret<tensor<9xi32>>
        !outputvec   = !secret.secret<tensor<{output_elems}xi32>>

        func.func @main(%img : !inputvec, %filter : !filterinput) -> !outputvec {{
            %cn = arith.constant {N} : !val

            %img_dyn = secret.generic(%img : !inputvec) {{
            ^bb0(%a: tensor<{input_elems}xi32>):
                %cast = tensor.cast %a : tensor<{input_elems}xi32> to tensor<?xi32>
                secret.yield %cast : tensor<?xi32>
            }} -> !svec

            %filter_dyn = secret.generic(%filter : !filterinput) {{
            ^bb0(%a: tensor<9xi32>):
                %cast = tensor.cast %a : tensor<9xi32> to tensor<?xi32>
                secret.yield %cast : tensor<?xi32>
            }} -> !svec

            %result_dyn = call @conv(%img_dyn, %filter_dyn, %cn)
                {{ biscotti.call = 0 }} : (!svec, !svec, !val) -> !svec

            %result_static = secret.generic(%result_dyn : !svec) {{
            ^bb0(%r: tensor<?xi32>):
                %cast = tensor.cast %r : tensor<?xi32> to tensor<{output_elems}xi32>
                secret.yield %cast : tensor<{output_elems}xi32>
            }} -> !outputvec

            return %result_static : !outputvec
        }}
        """)


def main():
  ap = argparse.ArgumentParser(
      description=__doc__,
      formatter_class=argparse.RawDescriptionHelpFormatter,
  )
  ap.add_argument(
      "N",
      nargs="?",
      type=int,
      help="image side length (must be on the recursion ladder)",
  )
  ap.add_argument(
      "-o", "--output", help="output path (default: src/conv_<N>.mlir)"
  )
  ap.add_argument(
      "--all",
      action="store_true",
      help=f"emit all default sizes: {DEFAULT_SIZES}",
  )
  args = ap.parse_args()

  here = os.path.dirname(os.path.abspath(__file__))
  src_dir = os.path.join(here, "src")
  os.makedirs(src_dir, exist_ok=True)

  if args.all:
    for n in DEFAULT_SIZES:
      path = os.path.join(src_dir, f"conv_{n}.mlir")
      with open(path, "w") as f:
        f.write(emit_mlir(n))
      print(f"wrote {path}")
    return

  if args.N is None:
    ap.error("give a size N (or --all)")
  path = args.output or os.path.join(src_dir, f"conv_{args.N}.mlir")
  with open(path, "w") as f:
    f.write(emit_mlir(args.N))
  print(f"wrote {path}")


if __name__ == "__main__":
  main()
