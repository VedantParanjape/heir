#!/usr/bin/env python3
"""
Emit a recursive argmax MLIR file for a given array length N.

Input to the kernel: NxN column-major bit matrix (encrypted).
  bits[j * N + i] = 1 if arr[i] > arr[j] else 0 (with diagonal = 1).

Output: length-N one-hot vector `[b_0, ..., b_{N-1}]`. b_i is the
product of bits in column-major "row i across all N columns" — but
because we store column-major, "row i" is elements at index N*j + i for
j = 0..N-1. Equivalently: for each output slot i, product of one
element from each of the N columns, all at position i.

Recursion shape (2-way divide-and-conquer over COLUMNS):

  * @argmax(cols, k)  with `k` as the `biscotti.progress_argument`.
    `cols` is a k*N-element tensor holding k contiguous columns of the
    bit matrix, each column being N elements (one per output slot).
  * Base case (k == 2): element-wise mul of col[0] and col[1] → tensor
    of length N containing the per-slot partial product.
  * Recursive branch (k > 2): split cols into halves of k/2 columns each,
    recurse both, element-wise mul the two length-N sub-results.

This exploits TWO parallelism axes simultaneously:
  - NW-merge packs sibling recursive calls (log N levels of 2-way
    sibling packing across the tree).
  - Coyote's per-tensor packing spreads the N-row dimension across
    ciphertext lanes at every element-wise mul.
Combined: log(N) depth, fully vectorized at every level.

Size ladder: dense at low end to test odd-column splits (5, 6, 7 → odd
k values propagate), then powers of 2 for scale.

Usage:
  python3 gen_argmax.py 16                # writes src/argmax_16.mlir
  python3 gen_argmax.py --all             # writes src/argmax_{4,5,...}.mlir
  python3 gen_argmax.py 32 -o path.mlir   # explicit output path
"""

import argparse
import os
import textwrap

DEFAULT_SIZES = [4, 5, 6, 7, 8, 16, 32, 64, 128, 256]


def emit_flat_base_case(N: int) -> str:
  """Return MLIR for a flat (non-recursive) argmax at very small N.

  Emitted for N <= 2 (recursive template's base needs k >= 2, and at
  N == 2 the whole computation IS the base case with nothing to
  recurse over). Kernel is a top-level @main only — no @argmax at all,
  mirroring how conv_3 and max_2 handle their smallest cases.
  """
  assert N == 2, f"flat base emitter only fires at N == 2, got {N}"

  return textwrap.dedent(f"""\
        // Flat (non-recursive) argmax at N=2. Emitted here because the
        // recursive template's @argmax needs k>=2 columns to work with,
        // and at N=2 the whole computation IS the k=2 base case with
        // nothing to recurse over.
        //
        // Generated by benchmarks/argmax/gen_argmax.py — do not hand-edit.
        //
        // Input: 4-element bit matrix (2x2 column-major, encrypted).
        // Output: 2-element one-hot.

        !inputvec  = !secret.secret<tensor<4xi32>>
        !outputvec = !secret.secret<tensor<2xi32>>

        func.func @main(%bits : !inputvec) -> !outputvec {{
            %result = secret.generic(%bits : !inputvec) {{
            ^body(%b: tensor<4xi32>):
                // col0 = b[0..2], col1 = b[2..4]
                %col0 = tensor.extract_slice %b[0][2][1] : tensor<4xi32> to tensor<2xi32>
                %col1 = tensor.extract_slice %b[2][2][1] : tensor<4xi32> to tensor<2xi32>
                // Element-wise mul (per-row product across the 2 cols).
                %out = arith.muli %col0, %col1 : tensor<2xi32>
                secret.yield %out : tensor<2xi32>
            }} -> !outputvec

            return %result : !outputvec
        }}
        """)


def emit_mlir(N: int) -> str:
  """Return MLIR for a recursive argmax over an N-element array."""
  if N < 2:
    raise ValueError(f"N must be >= 2, got {N}")

  if N == 2:
    return emit_flat_base_case(N)

  total_bits = N * N

  return textwrap.dedent(f"""\
        // Recursive 2-way divide-and-conquer argmax over an N={N} array.
        // Kernel input: N*N = {total_bits} column-major pairwise bits
        // (encrypted). Output: N={N} one-hot vector.
        //
        // At each recursion level, columns get split into two halves;
        // element-wise product combines sub-results into a length-N
        // partial product. Base case (k==2) is a single element-wise
        // mul of two adjacent columns. Log(N) tree depth, fully
        // vectorized via coyote's per-tensor packing + biscotti's
        // NW-merge across siblings.
        //
        // Generated by benchmarks/argmax/gen_argmax.py — do not hand-edit.

        !val  = i32
        !svec = !secret.secret<tensor<?x!val>>

        // Column count k of THIS call is the biscotti progress argument.
        // The kernel doesn't need N (the row count / one-hot length) as
        // a runtime value — it's implicit in the tensor shape: cols has
        // k * N bits, so N = total_size / k. We pass k in as the
        // progress arg so the recursion pass can specialize each depth
        // level.
        //
        // %n_val holds the fixed row count N ({N}) so we can compute
        // sub-slice sizes: sub-cols carries k' * N bits.
        func.func @argmax(
            %cols : !svec,
            %k    : !val {{ biscotti.progress_argument = 1 }}
        ) -> !svec {{

            %c2v = arith.constant 2 : !val
            %n_val = arith.constant {N} : !val

            %cond = arith.cmpi sle, %k, %c2v : !val
            cf.cond_br %cond, ^base, ^recursive {{ biscotti.base_condition = 0 }}

        ^base:
            // k == 2: element-wise mul of the two contiguous columns.
            // cols contains 2*N = {2 * N} bits: col0 = cols[0..N],
            // col1 = cols[N..2N]. Result is a length-N tensor
            // holding per-row (col0[i] * col1[i]).
            %result_base = secret.generic(%cols : !svec) {{
                ^bb0(%c: tensor<?x!val>):
                    %n_idx = arith.constant {N} : index

                    // Extract col0 into a length-N tensor via tensor.generate.
                    %col0 = tensor.generate %n_idx {{
                        ^bb0(%i: index):
                            %v = tensor.extract %c[%i] : tensor<?x!val>
                            tensor.yield %v : !val
                    }} : tensor<?x!val>

                    // Extract col1 similarly, offset by N.
                    %col1 = tensor.generate %n_idx {{
                        ^bb0(%i: index):
                            %src = arith.addi %i, %n_idx : index
                            %v = tensor.extract %c[%src] : tensor<?x!val>
                            tensor.yield %v : !val
                    }} : tensor<?x!val>

                    // Element-wise multiply → length-N partial product.
                    %prod = arith.muli %col0, %col1 : tensor<?x!val>
                    secret.yield %prod : tensor<?x!val>
            }} -> (!svec)
            return %result_base : !svec

        ^recursive:
            // k > 2: split cols at k/2. Left half is cols[0..(k/2)*N],
            // right half is cols[(k/2)*N..k*N]. Each recursive call
            // handles k/2 (or k - k/2 for odd k) columns and returns a
            // length-N partial product. Element-wise mul combines them.
            %half        = arith.divsi %k, %c2v : !val
            %rest        = arith.subi %k, %half : !val
            %half_cols   = arith.muli %half, %n_val : !val
            %rest_cols   = arith.muli %rest, %n_val : !val

            %half_cols_idx = arith.index_cast %half_cols : !val to index
            %rest_cols_idx = arith.index_cast %rest_cols : !val to index
            %n_idx         = arith.constant {N} : index

            // Extract left half of columns: cols[0..half*N].
            %left_bits = secret.generic(%cols : !svec, %half_cols_idx : index) {{
                ^bb0(%c: tensor<?x!val>, %h: index):
                    %out = tensor.generate %h {{
                        ^bb0(%i: index):
                            %v = tensor.extract %c[%i] : tensor<?x!val>
                            tensor.yield %v : !val
                    }} : tensor<?x!val>
                    secret.yield %out : tensor<?x!val>
            }} -> (!svec)

            // Extract right half of columns: cols[half*N..k*N].
            %right_bits = secret.generic(%cols : !svec,
                                         %half_cols_idx : index,
                                         %rest_cols_idx : index) {{
                ^bb0(%c: tensor<?x!val>, %h: index, %r: index):
                    %out = tensor.generate %r {{
                        ^bb0(%i: index):
                            %src = arith.addi %i, %h : index
                            %v = tensor.extract %c[%src] : tensor<?x!val>
                            tensor.yield %v : !val
                    }} : tensor<?x!val>
                    secret.yield %out : tensor<?x!val>
            }} -> (!svec)

            // Recurse on each half.
            %left  = call @argmax(%left_bits,  %half) {{ biscotti.recursive_call = 0 }} : (!svec, !val) -> !svec
            %right = call @argmax(%right_bits, %rest) {{ biscotti.recursive_call = 1 }} : (!svec, !val) -> !svec

            // Element-wise multiply the two length-N partial products.
            %result = secret.generic(%left : !svec, %right : !svec) {{
                ^bb0(%l: tensor<?x!val>, %r: tensor<?x!val>):
                    %out = tensor.generate %n_idx {{
                        ^bb0(%i: index):
                            %lv = tensor.extract %l[%i] : tensor<?x!val>
                            %rv = tensor.extract %r[%i] : tensor<?x!val>
                            %m = arith.muli %lv, %rv : !val
                            tensor.yield %m : !val
                    }} : tensor<?x!val>
                    secret.yield %out : tensor<?x!val>
            }} -> (!svec)

            return %result : !svec
        }}

        // Entry: N*N bit matrix (column-major) → length-N one-hot.
        !inputvec  = !secret.secret<tensor<{total_bits}xi32>>
        !outputvec = !secret.secret<tensor<{N}xi32>>

        func.func @main(%bits : !inputvec) -> !outputvec {{
            %ck = arith.constant {N} : !val

            %bits_dyn = secret.generic(%bits : !inputvec) {{
            ^bb0(%b: tensor<{total_bits}xi32>):
                %cast = tensor.cast %b : tensor<{total_bits}xi32> to tensor<?xi32>
                secret.yield %cast : tensor<?xi32>
            }} -> !svec

            %result_dyn = call @argmax(%bits_dyn, %ck)
                {{ biscotti.call = 0 }} : (!svec, !val) -> !svec

            %result_static = secret.generic(%result_dyn : !svec) {{
            ^bb0(%r: tensor<?xi32>):
                %cast = tensor.cast %r : tensor<?xi32> to tensor<{N}xi32>
                secret.yield %cast : tensor<{N}xi32>
            }} -> !outputvec

            return %result_static : !outputvec
        }}
        """)


def main():
  ap = argparse.ArgumentParser(
      description=__doc__,
      formatter_class=argparse.RawDescriptionHelpFormatter,
  )
  ap.add_argument("N", nargs="?", type=int, help="array length (N >= 2)")
  ap.add_argument(
      "-o", "--output", help="output path (default: src/argmax_<N>.mlir)"
  )
  ap.add_argument(
      "--all",
      action="store_true",
      help=f"emit all default sizes: {DEFAULT_SIZES}",
  )
  args = ap.parse_args()

  here = os.path.dirname(os.path.abspath(__file__))
  src_dir = os.path.join(here, "src")
  os.makedirs(src_dir, exist_ok=True)

  if args.all:
    for n in DEFAULT_SIZES:
      path = os.path.join(src_dir, f"argmax_{n}.mlir")
      with open(path, "w") as f:
        f.write(emit_mlir(n))
      print(f"wrote {path}")
    return

  if args.N is None:
    ap.error("give a size N (or --all)")
  path = args.output or os.path.join(src_dir, f"argmax_{args.N}.mlir")
  with open(path, "w") as f:
    f.write(emit_mlir(args.N))
  print(f"wrote {path}")


if __name__ == "__main__":
  main()
